/**
 * Format string tanggal YYYY-MM-DD ke format Indonesia (contoh: 25 September 2026)
 */
export function formatTanggalIndonesia(dateString?: string | null): string {
  if (!dateString) return "-";
  try {
    const date = new Date(dateString);
    if (isNaN(date.getTime())) return dateString;
    return date.toLocaleDateString("id-ID", {
      day: "numeric",
      month: "long",
      year: "numeric",
    });
  } catch {
    return dateString;
  }
}
